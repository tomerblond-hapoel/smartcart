/**
 * Direct DB fallback used when curl cannot make an internal HTTP call
 * (e.g. server blocks loopback requests).  Mirrors webhook.php logic.
 */
function process_payment_directly(PDO $pdo, int $payment_id, string $new_status): void
{
    $pdo->beginTransaction();
    try {
        $stmt = $pdo->prepare("SELECT * FROM payments WHERE id = ? FOR UPDATE");
        $stmt->execute([$payment_id]);
        $pay  = $stmt->fetch();
        if (!$pay) { $pdo->rollBack(); return; }

        if (in_array($pay['status'], ['paid', 'completed', 'failed'], true)) {
            $pdo->rollBack(); return;
        }

        if ($new_status === 'paid') {
            $pdo->prepare("UPDATE payments SET status='paid', paid_at=NOW() WHERE id=?")
                ->execute([$payment_id]);

            $product_id = (int)($pay['product_id'] ?? 0);
            if (!$product_id) {
                $ps = $pdo->prepare("SELECT product_id FROM group_purchases WHERE id=?");
                $ps->execute([$pay['group_id']]);
                $product_id = (int)($ps->fetchColumn() ?: 0);
            }

            $pdo->prepare("UPDATE group_members SET status='paid' WHERE group_id=? AND user_id=?")
                ->execute([$pay['group_id'], $pay['user_id']]);

            if ($product_id) {
                $pdo->prepare("INSERT IGNORE INTO orders (group_id, payment_id, user_id, product_id, amount_paid, shipping_status) VALUES (?,?,?,?,?,'pending')")
                    ->execute([$pay['group_id'], $payment_id, $pay['user_id'], $product_id, $pay['amount_ils']]);
            }
            $pdo->commit();

            // Check all-paid
            $s = $pdo->prepare("SELECT COUNT(*) AS t, SUM(CASE WHEN status='paid' THEN 1 ELSE 0 END) AS p FROM group_members WHERE group_id=?");
            $s->execute([$pay['group_id']]);
            $r = $s->fetch();
            if ($r && (int)$r['t'] > 0 && (int)$r['p'] >= (int)$r['t']) {
                $pdo->prepare("UPDATE group_purchases SET status='order_ready' WHERE id=? AND status='ready_for_payment'")
                    ->execute([$pay['group_id']]);
            }
        } else {
            $pdo->prepare("UPDATE payments SET status='failed' WHERE id=?")->execute([$payment_id]);
            $pdo->commit();
        }
    } catch (\Throwable $e) {
        if ($pdo->inTransaction()) $pdo->rollBack();
        PaymentService::log('mock_direct_error', ['error' => $e->getMessage()]);
    }
}
