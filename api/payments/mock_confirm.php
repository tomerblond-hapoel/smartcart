// ── Handle POST actions ────────────────────────────────────────────────────
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $action = $_POST['mock_action'] ?? '';

    if ($action === 'pay' || $action === 'fail') {
        $new_status = $action === 'pay' ? 'paid' : 'failed';

        // Call the webhook handler via an internal HTTP POST so all the
        // DB logic stays in one place.  Fall back to direct DB call if
        // curl / allow_url_fopen is disabled on the server.
        $webhook_url = APP_URL . '/api/payments/webhook.php';
        $secret      = defined('PAYMENT_WEBHOOK_SECRET') ? PAYMENT_WEBHOOK_SECRET : '';
        $payload     = json_encode([
            'payment_id'     => $payment_id,
            'transaction_id' => $pay['provider_transaction_id'] ?? '',
            'status'         => $new_status,
        ]);

        $sent = false;
        if (function_exists('curl_init')) {
            $ch = curl_init($webhook_url);
            curl_setopt_array($ch, [
                CURLOPT_RETURNTRANSFER => true,
                CURLOPT_POST           => true,
                CURLOPT_POSTFIELDS     => $payload,
                CURLOPT_HTTPHEADER     => [
                    'Content-Type: application/json',
                    'X-Webhook-Token: ' . $secret,
                ],
                CURLOPT_TIMEOUT        => 10,
            ]);
            $resp = curl_exec($ch);
            $code = curl_getinfo($ch, CURLINFO_HTTP_CODE);
            curl_close($ch);
            $sent = ($code >= 200 && $code < 300);
        }

        if (!$sent) {
            // Direct DB path (same logic as webhook handler)
            require_once __DIR__ . '/../../includes/notifications.php';
            process_payment_directly($pdo, $payment_id, $new_status);
        }

        if ($new_status === 'paid') {
            $redirect = defined('PAYMENT_SUCCESS_URL')
                ? PAYMENT_SUCCESS_URL . '?payment_id=' . $payment_id
                : APP_URL . '/pages/my-orders.php';
        } else {
            $redirect = $group_url . '&payment_failed=1';
        }

        header('Location: ' . $redirect);
        exit;
    }

    if ($action === 'cancel') {
        header('Location: ' . $group_url . '&cancelled=1');
        exit;
    }
}

